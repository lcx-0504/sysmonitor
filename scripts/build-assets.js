'use strict';
const fs = require('node:fs');
const path = require('node:path');
require('./build-translations');
const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'package.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
manifest.contributes.configuration.properties = require('../src/config/config-schema').manifestConfiguration();
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

function writeBrowserModule(source, target) {
  const names = Object.keys(require(path.join(root, source))).join(', ');
  const code = fs.readFileSync(path.join(root, source), 'utf8');
  fs.writeFileSync(path.join(root, target),
    '// Generated by scripts/build-assets.js from ' + source + '.\n' +
    'const { ' + names + ' } = ((module) => {\n' + code +
    '\nreturn module.exports;\n})({ exports: {} });\nexport { ' + names + ' };\n');
}

writeBrowserModule('src/core/metric-playback.js', 'src/view/assets/metric-playback.mjs');
writeBrowserModule('src/view/protocol.js', 'src/view/assets/protocol.mjs');
writeBrowserModule('src/domain/device-id.js', 'src/view/assets/device-id.mjs');
