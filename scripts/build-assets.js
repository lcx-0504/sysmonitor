'use strict';
// Regenerates files derived from the sources: `node scripts/build-assets.js` writes them, and
// `node scripts/build-assets.js --check` only reports the ones that differ and exits with status 1.
const fs = require('node:fs');
const path = require('node:path');
const { translationOutputs } = require('./build-translations');
const { manifestConfiguration } = require('../src/config/config-schema');

const projectRoot = path.resolve(__dirname, '..');
const BROWSER_MODULES = [
  ['src/core/metric-playback.js', 'src/view/assets/metric-playback.mjs'],
  ['src/view/protocol.js', 'src/view/assets/protocol.mjs'],
  ['src/domain/device-id.js', 'src/view/assets/device-id.mjs'],
];

function readProjectFile(file) {
  try {
    return fs.readFileSync(path.join(projectRoot, file), 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

// Only the configuration section of the manifest is generated; the rest is maintained by hand.
function manifestOutput() {
  const properties = manifestConfiguration();
  const configurationSection = (text) => JSON.stringify(JSON.parse(text).contributes.configuration.properties);
  const manifest = JSON.parse(readProjectFile('package.json'));
  manifest.contributes.configuration.properties = properties;
  return {
    file: 'package.json',
    content: JSON.stringify(manifest, null, 2) + '\n',
    isCurrent: (text) => configurationSection(text) === JSON.stringify(properties),
  };
}

function browserModuleOutput(source, target) {
  const names = Object.keys(require(path.join(projectRoot, source))).join(', ');
  const code = readProjectFile(source);
  return {
    file: target,
    content: '// Generated by scripts/build-assets.js from ' + source + '.\n' +
      'const { ' + names + ' } = ((module) => {\n' + code +
      '\nreturn module.exports;\n})({ exports: {} });\nexport { ' + names + ' };\n',
  };
}

function generatedOutputs() {
  return [
    manifestOutput(),
    ...translationOutputs(),
    ...BROWSER_MODULES.map(([source, target]) => browserModuleOutput(source, target)),
  ];
}

function isCurrent(output) {
  const text = readProjectFile(output.file);
  if (text === null) return false;
  return output.isCurrent ? output.isCurrent(text) : text === output.content;
}

function main(args) {
  const stale = generatedOutputs().filter((output) => !isCurrent(output));
  if (args.includes('--check')) {
    if (!stale.length) return 0;
    for (const { file } of stale) process.stderr.write(`${file} is out of date with its sources.\n`);
    process.stderr.write('Run `npm run build` to regenerate the generated files.\n');
    return 1;
  }
  for (const { file, content } of stale) {
    fs.writeFileSync(path.join(projectRoot, file), content);
    process.stdout.write(`Updated ${file}\n`);
  }
  return 0;
}

process.exitCode = main(process.argv.slice(2));
