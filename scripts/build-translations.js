'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { catalogs } = require('../src/i18n');
for (const [locale, dictionary] of Object.entries(catalogs)) {
  const suffix = locale === 'en' ? '' : '.' + locale.toLowerCase();
  fs.writeFileSync(path.join(__dirname, '..', 'package.nls' + suffix + '.json'), JSON.stringify(dictionary.manifest, null, 2) + '\n');
}
const sourceDirectory = path.join(__dirname, '..', 'src', 'i18n');
const browserCatalogs = fs.readFileSync(path.join(sourceDirectory, 'catalogs.js'), 'utf8');
const browserRuntime = fs.readFileSync(path.join(sourceDirectory, 'index.js'), 'utf8');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'view', 'assets', 'i18n.mjs'),
  '// Generated by scripts/build-translations.js from src/i18n.\n' +
  'const catalogData = ((module) => {\n' + browserCatalogs + '\nreturn module.exports;\n})({ exports: {} });\n' +
  'const { catalogs, resolveLanguage, createTranslator, localizeError } = ((module, require) => {\n' + browserRuntime +
  '\nreturn module.exports;\n})({ exports: {} }, name => {\n' +
  'if (name !== "./catalogs") throw new Error("Unknown translation dependency: " + name);\nreturn catalogData;\n});\n' +
  'export { catalogs, resolveLanguage, createTranslator, localizeError };\n');
