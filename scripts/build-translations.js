'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { catalogs } = require('../src/i18n');

const projectRoot = path.resolve(__dirname, '..');

function manifestLocalizations() {
  return Object.entries(catalogs).map(([locale, dictionary]) => {
    const suffix = locale === 'en' ? '' : '.' + locale.toLowerCase();
    return { file: 'package.nls' + suffix + '.json', content: JSON.stringify(dictionary.manifest, null, 2) + '\n' };
  });
}

function browserTranslations() {
  const sourceDirectory = path.join(projectRoot, 'src', 'i18n');
  const browserCatalogs = fs.readFileSync(path.join(sourceDirectory, 'catalogs.js'), 'utf8');
  const browserRuntime = fs.readFileSync(path.join(sourceDirectory, 'index.js'), 'utf8');
  return {
    file: 'src/view/assets/i18n.mjs',
    content: '// Generated by scripts/build-translations.js from src/i18n.\n' +
      'const catalogData = ((module) => {\n' + browserCatalogs + '\nreturn module.exports;\n})({ exports: {} });\n' +
      'const { catalogs, resolveLanguage, createTranslator, localizeError } = ((module, require) => {\n' + browserRuntime +
      '\nreturn module.exports;\n})({ exports: {} }, name => {\n' +
      'if (name !== "./catalogs") throw new Error("Unknown translation dependency: " + name);\nreturn catalogData;\n});\n' +
      'export { catalogs, resolveLanguage, createTranslator, localizeError };\n',
  };
}

// Files generated from src/i18n, as paths relative to the project root with their expected content.
function translationOutputs() {
  return [...manifestLocalizations(), browserTranslations()];
}

module.exports = { translationOutputs };
